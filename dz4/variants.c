#include <stdio.h>
#define N 111260275 //номер студбилета

int main(void){
    printf("Варианты: \n");
    printf("4.1 : %d \n", (N % 30) + 1);
    printf("4.2 : %d \n", ((N + 7) % 30) + 1);
    printf("4.3 : %d \n", ((N + 13) % 30) + 1);
    printf("4.4 : %d \n", ((N + 19) % 30) + 1);
    printf("4.5 : %d \n", ((N + 23) % 30) + 1);
    return 0;
}

